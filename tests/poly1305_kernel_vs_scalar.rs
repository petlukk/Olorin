//! Poly1305 kernel vs scalar parity test.
//!
//! Compares the Eä SIMD kernel output against the scalar reference
//! implementation for 200 deterministic-PRNG random (key, msg) pairs
//! and all 11 RFC 8439 §A.3 test vectors.

mod poly1305_scalar;

use olorin::kernels::ffi;

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

fn kernel_mac(key: &[u8; 32], msg: &[u8]) -> [u8; 16] {
    let mut tag = [0u8; 16];
    unsafe {
        ffi::poly1305_mac(key.as_ptr(), msg.as_ptr(), msg.len() as i32, tag.as_mut_ptr());
    }
    tag
}

fn scalar_mac(key: &[u8; 32], msg: &[u8]) -> [u8; 16] {
    let mut tag = [0u8; 16];
    poly1305_scalar::poly1305_mac(key, msg, &mut tag);
    tag
}

fn hex(s: &str) -> Vec<u8> {
    let s: String = s.chars().filter(|c| !c.is_whitespace()).collect();
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("valid hex"))
        .collect()
}

/// Minimal LCG PRNG — deterministic across platforms.
fn lcg_next(state: &mut u64) -> u8 {
    *state = state.wrapping_mul(6364136223846793005).wrapping_add(1442695040888963407);
    ((*state >> 33) ^ (*state >> 17)) as u8
}

// ---------------------------------------------------------------------------
// 200-vector random sweep
// ---------------------------------------------------------------------------

#[test]
fn kernel_matches_scalar_random_inputs() {
    olorin::kernels::ffi::init().expect("kernel init");

    let mut prng: u64 = 0xdeadbeef_cafebabe;

    for trial in 0..200u32 {
        // Generate a random 32-byte key.
        let mut key = [0u8; 32];
        for b in &mut key {
            *b = lcg_next(&mut prng);
        }

        // Generate a random message length in [0, 1024].
        let len_hi = lcg_next(&mut prng) as usize;
        let len_lo = lcg_next(&mut prng) as usize;
        let msg_len = (len_hi * 256 + len_lo) & 1023;

        // Generate the message bytes.
        let mut msg = vec![0u8; msg_len];
        for b in &mut msg {
            *b = lcg_next(&mut prng);
        }

        let scalar_tag = scalar_mac(&key, &msg);
        let kernel_tag = kernel_mac(&key, &msg);

        assert_eq!(
            scalar_tag,
            kernel_tag,
            "trial {trial}: tag mismatch for msg_len={msg_len}\n  key:    {:02x?}\n  scalar: {:02x?}\n  kernel: {:02x?}",
            &key,
            &scalar_tag,
            &kernel_tag,
        );
    }
}

// ---------------------------------------------------------------------------
// RFC 8439 §A.3 test vectors (all 11)
// ---------------------------------------------------------------------------

fn run_rfc(key_hex: &str, msg: &[u8], expected_hex: &str) {
    olorin::kernels::ffi::init().expect("kernel init");

    let key_bytes = hex(key_hex);
    let key: &[u8; 32] = key_bytes.as_slice().try_into().expect("32-byte key");
    let expected = hex(expected_hex);
    let tag = kernel_mac(key, msg);
    assert_eq!(
        tag.as_ref(),
        expected.as_slice(),
        "RFC tag mismatch\n  got:      {:02x?}\n  expected: {:02x?}",
        &tag,
        expected.as_slice(),
    );
}

