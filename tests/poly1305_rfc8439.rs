//! RFC 8439 §A.3 — Poly1305 test vectors (all 11 cases).
//!
//! The scalar reference lives in `poly1305_scalar.rs` (sibling module).
//! Every test calls `poly1305_scalar::poly1305_mac` and asserts
//! byte-exact equality with the expected tag from the RFC.

mod poly1305_scalar;

fn hex(s: &str) -> Vec<u8> {
    let s: String = s.chars().filter(|c| !c.is_whitespace()).collect();
    (0..s.len())
        .step_by(2)
        .map(|i| u8::from_str_radix(&s[i..i + 2], 16).expect("valid hex"))
        .collect()
}

fn run(key_hex: &str, msg: &[u8], expected_hex: &str) {
    let key_bytes = hex(key_hex);
    let key: &[u8; 32] = key_bytes
        .as_slice()
        .try_into()
        .expect("key must be 32 bytes");
    let expected = hex(expected_hex);
    let mut tag = [0u8; 16];
    poly1305_scalar::poly1305_mac(key, msg, &mut tag);
    assert_eq!(
        tag.as_ref(),
        expected.as_slice(),
        "tag mismatch\n  got:      {:02x?}\n  expected: {:02x?}",
        &tag,
        expected.as_slice(),
    );
}

