//! report — self-contained HTML report renderer, the fourth consumer of
//! the RuneOutput v1 contract (REPL text, web chart, `--json`, this).
//!
//! One .html file, inline CSS, inline SVG, zero external assets, zero
//! JavaScript — it opens anywhere, prints cleanly, and survives being
//! emailed. Charts consume the same `col_reduce`-kernel-reduced column
//! envelope as the block-bar renderer (`plot::columnize`), so every
//! presentation surface agrees about the data.
//!
//! Deliberately deterministic: no wall-clock timestamp, no model
//! narration — same inputs produce the same bytes, so reports golden-
//! test like every other rune output. Every file-derived string is
//! HTML-escaped.

use super::output::RuneOutput;
use super::plot;

/// One analyzed file: the friendly name, the rune that ran, its output.
pub struct ReportSection {
    pub display: String,
    pub rune:    String,
    pub output:  RuneOutput,
}

